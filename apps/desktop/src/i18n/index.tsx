const I18nContext = createContext<I18nContextValue | null>(null)

let currentDesktopLocale: DesktopLocale = "en"

export function getCurrentDesktopLocale() {
  return currentDesktopLocale
}

export function setCurrentDesktopLocale(locale: DesktopLocale) {
  currentDesktopLocale = locale
}

export function parseLocaleMode(value: unknown): LocaleMode {
  return value === "zh-CN" || value === "en" || value === "system" ? value : "system"
}

export function detectSystemLocale(languages: readonly string[] = browserLanguages()): DesktopLocale {
  for (const language of languages) {
    const normalized = language.trim().replace("_", "-").toLowerCase()
    if (!normalized) continue
    if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN"
    if (normalized === "en" || normalized.startsWith("en-")) return "en"
  }
  return "zh-CN"
}

export function resolveLocale(mode: LocaleMode, languages?: readonly string[]): DesktopLocale {
  if (mode === "system") return detectSystemLocale(languages)
  return mode
}

export function translate(locale: DesktopLocale, key: string, values: Record<string, string | number> = {}) {
  const template = locale === "zh-CN" ? zhMessages[key] ?? key : key
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    const value = values[name]
    return value === undefined ? match : String(value)
  })
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [mode, setMode] = useState<LocaleMode>(() =>
    typeof window === "undefined" ? "system" : parseLocaleMode(window.localStorage.getItem(DESKTOP_LOCALE_STORAGE_KEY)),
  )
  const [systemLocale, setSystemLocale] = useState<DesktopLocale>(() => detectSystemLocale())
  const locale = resolveLocale(mode, [systemLocale])

  useEffect(() => {
    setCurrentDesktopLocale(locale)
  }, [locale])

  useEffect(() => {
    if (typeof window === "undefined") return
    window.localStorage.setItem(DESKTOP_LOCALE_STORAGE_KEY, mode)
  }, [mode])

  useEffect(() => {
    if (typeof window === "undefined") return
    const update = () => setSystemLocale(detectSystemLocale())
    window.addEventListener("languagechange", update)
    return () => window.removeEventListener("languagechange", update)
  }, [])

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      mode,
      setMode,
      t: (key, values) => translate(locale, key, values),
    }),
    [locale, mode],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  const fallbackContext: I18nContextValue = {
    locale: "en",
    mode: "en",
    setMode: (mode) => setCurrentDesktopLocale(resolveLocale(mode)),
    t: (key, values) => translate("en", key, values),
  }
  return context ?? fallbackContext
}

function browserLanguages() {
  if (typeof navigator === "undefined") return []
  if (navigator.languages?.length) return navigator.languages
  return navigator.language ? [navigator.language] : []
}
